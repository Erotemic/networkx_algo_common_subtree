#!/usr/bin/env python3
"""Regenerate the lookup operational program and its real extra-work mutation.

Uses the existing pinned Charon binary; does not modify production Rust or its
Aeneas-generated semantics. The mutant is compiled in a temporary copied crate.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

from reify_lookup_llbc import Reifier
import json


def source_lean(data, namespace, *, root_namespace="SubtreeProofs.Rust.LookupSource.Input",
                source_filename="lookup.llbc", generator="dev/regenerate_lookup_source.py"):
    """Embed the source JSON as data, retaining all statements and metadata.

    Only extraction output destinations are normalized: temporary directory
    names are not part of the LLBC program. The Lean reader does not consume
    these two fields. Function/type declarations, source text, branch indices,
    spans, operands and unwind blocks are otherwise retained verbatim as JSON.
    """
    snapshot = json.loads(json.dumps(data))
    snapshot["translated"]["options"]["dest_dir"] = "."
    snapshot["translated"]["options"]["dest_file"] = source_filename
    literal = json.dumps(snapshot, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(literal.encode()).hexdigest()
    # Keep the entire JSON value, but split its Lean expression into data
    # declarations. A single enormous json% term exceeds elaborator recursion
    # limits even though the source syntax itself is shallow.
    definitions = []

    def render(value):
        if isinstance(value, dict):
            result = "{" + ",".join(json.dumps(key, ensure_ascii=False) + ":" + render(value[key])
                                     for key in sorted(value)) + "}"
        elif isinstance(value, list):
            result = "[" + ",".join(render(item) for item in value) + "]"
        else:
            result = json.dumps(value, ensure_ascii=False)
        if len(result) > 2048:
            label = f"data{len(definitions)}"
            definitions.append(f"def {label} : Lean.Json := json% {result}\n")
            return f"$({label})"
        return result

    expression = render(snapshot)
    return (f"-- Generated by {generator}; do not edit.\n"
            f"-- Source JSON SHA-256 (output destinations normalized): {digest}\n"
            "module\npublic import Lean.Data.Json.Elab\n"
            "@[expose] public section\n"
            "set_option maxRecDepth 8192\nset_option maxHeartbeats 4000000\n"
            f"namespace {root_namespace}.{namespace}\n\n"
            + "\n".join(definitions) + f"\ndef source : Lean.Json := json% {expression}\n\n"
            f"end {root_namespace}.{namespace}\n")


def extract(charon: Path, crate: Path, llbc: Path):
    subprocess.run([str(charon), "cargo", "--preset=aeneas", "--start-from",
                    "verified_ordered_core::memo_lookup", "--no-dedup-serialized-ast",
                    "--dest-file", str(llbc)], cwd=crate, check=True,
                   env={**os.environ, "RUSTUP_TOOLCHAIN": "nightly-2026-09-17"})
    return json.loads(llbc.read_bytes())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--charon", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    charon = args.charon.resolve(strict=True)
    root = Path(__file__).resolve().parents[1]
    crate = root / "rust/crates/verified_ordered_core"
    maintained = root / "proofs/SubtreeProofs/Rust/Generated"
    with tempfile.TemporaryDirectory(prefix="subtree-lookup-source-") as temp:
        work = Path(temp)
        original = extract(charon, crate, work / "original.llbc")
        mutant = work / "mutant"
        mutant.mkdir()
        for file in ("Cargo.toml", "Cargo.lock"):
            shutil.copyfile(crate / file, mutant / file)
        for directory in ("src", "benches"):
            shutil.copytree(crate / directory, mutant / directory)
        lib = mutant / "src/lib.rs"
        source = lib.read_text()
        start = source.index("pub fn memo_lookup(")
        body = source.index("{", start) + 1
        lib.write_text(source[:body] + "\n    let _ = words_equal(left, left);\n" + source[body:])
        changed = extract(charon, mutant, work / "extra-compare.llbc")
        for data, namespace, filename in (
                (original, "Program", "LookupSourceProgram.lean"),
                (changed, "ExtraCompare", "LookupSourceExtraCompare.lean")):
            inputs = "LookupSourceInput.lean" if namespace == "Program" else "LookupSourceExtraCompareInput.lean"
            for filename, generated in ((filename, Reifier(data).lean(namespace)),
                                        (inputs, source_lean(data, namespace))):
                target = maintained / filename
                if args.check:
                    current = target.read_text()
                    if current != generated:
                        print("".join(difflib.unified_diff(current.splitlines(keepends=True),
                              generated.splitlines(keepends=True), fromfile=str(target),
                              tofile="fresh extraction")), end="")
                        raise SystemExit(1)
                else:
                    target.write_text(generated)


if __name__ == "__main__":
    main()
