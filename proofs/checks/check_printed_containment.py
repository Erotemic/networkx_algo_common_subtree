"""Independent finite check of Lozano--Valiente (2004), Definition 2.

This is a research/checking script, NOT a Lean proof or a replacement for one.
It compares the least relation generated by the printed recursive clauses
against the transitive closure of deleting matched parentheses pairs. Tokens
'0' and '1' stand for descending and ascending an edge, respectively.

Run: python3 proofs/checks/check_printed_containment.py
"""

from functools import lru_cache


def matching_pairs(word):
    stack = []
    pairs = []
    for j, token in enumerate(word):
        if token == "0":
            stack.append(j)
        else:
            assert token == "1" and stack
            pairs.append((stack.pop(), j))
    assert not stack
    return tuple(pairs)


def is_balanced(word):
    height = 0
    for ch in word:
        height += 1 if ch == "0" else -1
        if height < 0:
            return False
    return height == 0


@lru_cache(maxsize=None)
def printed_contained(word):
    """Smallest relation satisfying the printed Definition 2 clauses.

    Decompose word = t1 + '0' + t2 + '1' + t3, requiring all ti balanced,
    and combine independently contained s1, s2, s3.
    """
    results = {word}
    for i, j in matching_pairs(word):
        t1, t2, t3 = word[:i], word[i + 1 : j], word[j + 1 :]
        if not (is_balanced(t1) and is_balanced(t2) and is_balanced(t3)):
            continue
        for s1 in printed_contained(t1):
            for s2 in printed_contained(t2):
                for s3 in printed_contained(t3):
                    results.add(s1 + s2 + s3)
    return frozenset(results)


@lru_cache(maxsize=None)
def operational_contained(word):
    """Reflexive/transitive closure of deleting any matched pair."""
    results = {word}
    for i, j in matching_pairs(word):
        reduced = word[:i] + word[i + 1 : j] + word[j + 1 :]
        results.update(operational_contained(reduced))
    return frozenset(results)


@lru_cache(maxsize=None)
def dyck_words(edges):
    """All balanced words of semilength `edges` by first-return split."""
    if edges == 0:
        return ("",)
    return tuple(
        "0" + inside + "1" + outside
        for i in range(edges)
        for inside in dyck_words(i)
        for outside in dyck_words(edges - i - 1)
    )


def main():
    first = None
    for edges in range(6):
        words = dyck_words(edges)
        disagreements = []
        for word in words:
            paper = printed_contained(word)
            operational = operational_contained(word)
            assert paper <= operational, (word, paper - operational)
            if paper != operational:
                disagreements.append(word)
                if first is None:
                    first = (word, sorted(operational - paper))
        print(f"edges={edges}: {len(words)} inputs; "
              f"{len(disagreements)} containment disagreements")

    before, extra = first
    assert before == "001011", first
    assert "0011" in extra, first
    assert printed_contained("001011") == frozenset({"001011", "0101", "01", ""})
    assert operational_contained("001011") == frozenset({"001011", "0101", "0011", "01", ""})
    print("\nFirst counterexample:")
    print(f"  original: {before}")
    print(f"  operational only: {extra}")
    example = "00100100101111"  # Example 2 in the paper
    print("\nPaper Example 2:")
    print(f"  printed recurrence: {len(printed_contained(example))} words")
    print(f"  matching-pair deletion: {len(operational_contained(example))} words")
    assert len(printed_contained(example)) == 11
    assert len(operational_contained(example)) == 34


if __name__ == "__main__":
    main()
